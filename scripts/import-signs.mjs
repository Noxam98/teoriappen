// Imports the official Norwegian sign drawings (Statens vegvesen, public domain; the SVG files from Wikimedia Commons,
// named «NO road sign <number>.svg») into src/components/figures/signs/official.ts:
//   node scripts/import-signs.mjs <folder with the SVG files>
// Which sign is which: scripts/sign-numbers.json ({ "<key in the app>": "<sign number>" }).
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { optimize } from 'svgo';

const dir = process.argv[2];
if (!dir) throw new Error('usage: node scripts/import-signs.mjs <folder with «NO road sign …svg»>');
const root = new URL('..', import.meta.url).pathname;
const numbers = JSON.parse(readFileSync(join(root, 'scripts/sign-numbers.json'), 'utf8'));

const out = [];
let refs = 0;
for (const [key, nr] of Object.entries(numbers)) {
  const raw = readFileSync(join(dir, `NO road sign ${nr}.svg`), 'utf8');
  const { data } = optimize(raw, {
    multipass: true,
    floatPrecision: 4,
    plugins: [
      // transforms stay as they are: rounded (a scale of .125 → .13) the drawing grows too big for its box
      { name: 'preset-default', params: { overrides: { convertTransform: false } } },
      { name: 'prefixIds', params: { prefix: `s-${key}` } },
      'removeDimensions',
      { name: 'removeAttrs', params: { attrs: ['data-name', 'class'] } },
    ],
  });
  const vb = /<svg[^>]*\sviewBox="([^"]+)"/.exec(data)?.[1];
  if (!vb) throw new Error(`${nr}: no viewBox`);
  let body = data.replace(/^<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '');
  // a clip to the whole page (left over from the PDF the drawing came from) clips nothing the <svg> does not:
  // drop it, so no sign depends on an id elsewhere on the page (scripts/compare-signs.mjs checks the pixels)
  for (const [clip, id] of body.matchAll(/<clipPath id="([^"]+)"><path d="M[^"]*[zZ]"\/><\/clipPath>/g)) {
    body = body.replace(clip, '').replaceAll(` clip-path="url(#${id})"`, '');
  }
  body = body.replace(/<defs><\/defs>/g, '');
  refs += (body.match(/url\(#/g) ?? []).length;
  out.push(`  ${key}: { nr: '${nr}', vb: '${vb}', svg: ${JSON.stringify(body)} },`);
}
writeFileSync(join(root, 'src/components/figures/signs/official.ts'), `// Generated by scripts/import-signs.mjs — do not edit by hand.
// The official drawings of the Norwegian road signs (Statens vegvesen, public domain), via Wikimedia Commons.
// nr: the sign's number in skiltforskriften; vb: its viewBox; svg: what goes inside the <svg>.
export const OFFICIAL: Record<string, { nr: string; vb: string; svg: string }> = {
${out.join('\n')}
};
`);
console.log(`${out.length} signs, ${refs} url(#…) references`);
